/** Admin UI language: Italian and English. Separate from the public site (`ctrl-lang`, `/en/...`). */

export const ADMIN_LOCALES = ["it", "en"] as const;
export type AdminLocale = (typeof ADMIN_LOCALES)[number];
export const defaultAdminLocale: AdminLocale = "it";

/** Manual admin UI language. Path is `/admin` so the public site never sees it. */
export const ADMIN_LANG_COOKIE = "ctrl-admin-lang";

export const ADMIN_TIME_ZONE = "Europe/Rome";

export function isAdminLocale(value: unknown): value is AdminLocale {
  return value === "it" || value === "en";
}

export function parseAdminLocale(value: unknown): AdminLocale {
  return isAdminLocale(value) ? value : defaultAdminLocale;
}

export function adminIntlLocale(lang: AdminLocale): "it-IT" | "en-GB" {
  return lang === "en" ? "en-GB" : "it-IT";
}

export function interpolate(template: string, vars: Record<string, unknown>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

/** Dot keys of a nested dictionary (arrays become `.0`, `.1`, …). Used to check EN/IT parity. */
export function flattenDictKeys(value: unknown, prefix = ""): string[] {
  if (Array.isArray(value)) {
    return value.flatMap((item, i) => flattenDictKeys(item, prefix ? `${prefix}.${i}` : String(i)));
  }
  if (value !== null && typeof value === "object") {
    return Object.entries(value as Record<string, unknown>).flatMap(([key, item]) =>
      flattenDictKeys(item, prefix ? `${prefix}.${key}` : key),
    );
  }
  return prefix ? [prefix] : [];
}

function asDate(value: string | number | Date): Date | null {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

export function formatAdminDateTime(
  value: string | number | Date,
  lang: AdminLocale,
  options: Intl.DateTimeFormatOptions = { dateStyle: "medium", timeStyle: "short" },
): string {
  const date = asDate(value);
  if (!date) return "";
  return new Intl.DateTimeFormat(adminIntlLocale(lang), { timeZone: ADMIN_TIME_ZONE, ...options }).format(date);
}

export function formatAdminDate(
  value: string | number | Date,
  lang: AdminLocale,
  options: Intl.DateTimeFormatOptions = { day: "numeric", month: "short" },
): string {
  return formatAdminDateTime(value, lang, options);
}

export function formatAdminNumber(value: number, lang: AdminLocale, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(adminIntlLocale(lang), options).format(value);
}

export function formatAdminCurrency(
  value: number,
  lang: AdminLocale,
  options: Intl.NumberFormatOptions = {},
): string {
  return new Intl.NumberFormat(adminIntlLocale(lang), { style: "currency", currency: "EUR", ...options }).format(value);
}

export function formatAdminDateLabel(now: Date, lang: AdminLocale): string {
  const locale = adminIntlLocale(lang);
  return new Intl.DateTimeFormat(locale, {
    timeZone: ADMIN_TIME_ZONE,
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  })
    .format(now)
    .toLocaleUpperCase(locale);
}

export function formatAdminCountry(code: string, lang: AdminLocale, otherLabel: string): string {
  if (code === "altri") return otherLabel;
  try {
    return new Intl.DisplayNames([adminIntlLocale(lang)], { type: "region" }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

export function formatAdminShortAgo(iso: string, lang: AdminLocale, now = Date.now()): string {
  const t = adminDict[lang].time;
  const min = Math.round((now - Date.parse(iso)) / 60_000);
  if (!Number.isFinite(min)) return "";
  const m = Math.max(0, min);
  if (m < 1) return t.justNow;
  if (m < 60) return interpolate(t.minutesAgo, { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return interpolate(t.hoursAgo, { n: h });
  const d = Math.round(h / 24);
  if (d < 14) return interpolate(t.daysAgo, { n: d });
  return formatAdminDate(iso, lang, { timeZone: ADMIN_TIME_ZONE, day: "numeric", month: "short" });
}

