export function adminCrmSectionLabel(lang: AdminLocale, href: string): string {
  const t = adminDict[lang].crm;
  switch (href) {
    case "/admin/crm": return t.oggi;
    case "/admin/crm/rubrica": return t.rubrica;
    case "/admin/crm/pipeline": return t.pipeline;
    case "/admin/crm/radar": return t.radar;
    case "/admin/crm/attivita": return t.attivita;
    default: return t.eyebrow;
  }
}
export function adminCrmMailReturnLabel(lang: AdminLocale, origin: string): string {
  const labels = adminDict[lang].crm.mailReturn;
  return origin in labels ? labels[origin as keyof typeof labels] : labels.rubrica;
}
export function adminCrmCrumb(lang: AdminLocale, path: string): string | null {
  if (!path.startsWith("/admin/crm/")) return null;
  const [segment, sub] = path.slice("/admin/crm/".length).split("/");
  const t = adminDict[lang].crm;
  const section: Record<string, string> = { rubrica: t.rubrica, pipeline: t.pipeline, radar: t.radar, attivita: t.attivita };
  if (segment in section) return section[segment];
  return sub === "email" ? t.email : t.contactCard;
}
