export type AdminDict = (typeof adminDict)[AdminLocale];
export type AdminRoleKey = keyof AdminDict["roles"];
export type AdminAreaKey = keyof AdminDict["areas"];
export type AdminSearchGroupKey = keyof AdminDict["searchGroups"];

export function adminRoleLabel(lang: AdminLocale, role: string): string {
  const labels = adminDict[lang].roles;
  return role in labels ? labels[role as AdminRoleKey] : role;
}

export function adminAreaLabel(lang: AdminLocale, area: string): string {
  const labels = adminDict[lang].areas;
  return area in labels ? labels[area as AdminAreaKey] : area;
}

export function adminCrmStageLabel(lang: AdminLocale, stage: string): string {
  const labels = adminDict[lang].crm.stage;
  return stage in labels ? labels[stage as keyof typeof labels] : stage;
}
