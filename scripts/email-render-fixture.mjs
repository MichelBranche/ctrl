/*
 * Fixture check for email rendering (no network, no secrets):
 * builds a branded multipart MIME (html + text + cid logo) and a markdown-ish plain-text mail,
 * runs them through mailparser + the admin sanitizer, asserts the result, and writes the exact
 * iframe documents to OUT for screenshots.  Run: node scripts/email-render-fixture.mjs [OUT]
 */
import { registerHooks } from "node:module";
import { pathToFileURL } from "node:url";
import { mkdirSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";

const root = pathToFileURL(process.cwd() + "/").href;
registerHooks({
  resolve(spec, ctx, next) {
    if (spec === "server-only") return { url: "data:text/javascript,", shortCircuit: true };
    if (spec.startsWith("@/")) return next(new URL(spec.slice(2) + ".ts", root).href, ctx);
    return next(spec, ctx);
  },
});

const OUT = process.argv[2] ?? "/tmp/ctrl-email-render";
mkdirSync(OUT, { recursive: true });
const { brandedEmail, stripSignature } = await import("../lib/mail/template.ts");
const { sanitizeEmailHtml, emailDocument, textDocumentBody } = await import("../lib/mail/sanitize.ts");
const { default: MailComposer } = await import("nodemailer/lib/mail-composer/index.js");
const { simpleParser } = await import("mailparser");

const PNG = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8/5+hHgAHggJ/PchI7wAAAABJRU5ErkJggg==", "base64");
const body = "Buongiorno Laura,\n\ngrazie per la call. Ecco i **prossimi passi**:\n- bozza grafica entro venerdì\n- revisione insieme\n\nDettagli su https://ctrlagency.dev/servizi oppure scrivici a info@ctrlagency.dev.\n\n> Il 12 ottobre Laura ha scritto:\n> ci serve uno shop semplice";
const b = brandedEmail(body);
const html = b.html.replace(/<td style="font:900 22px[^>]*>C<\/td>/, '<td style="padding-right:10px"><img src="cid:ctrl-logo" alt="C" width="28" height="28"></td>') +
  '<script>alert(1)</script><img src="https://tracker.example/p.gif" width="1" height="1"><form action="https://x.example"><input></form><a href="#" onclick="steal()">x</a>';
const raw = await new MailComposer({ from: "Ctrl Agency <info@ctrlagency.dev>", to: "laura@example.test", subject: "Fixture brand", text: b.text, html,
  attachments: [{ filename: "logo.png", content: PNG, cid: "ctrl-logo", contentType: "image/png", contentDisposition: "inline" }] }).compile().build();
assert.match(raw.toString(), /multipart\/related|multipart\/alternative/);
const p = await simpleParser(raw, { skipTextToHtml: true, skipImageLinks: true });
assert.equal(typeof p.html, "string", "html part preferred");
const clean = sanitizeEmailHtml(String(p.html), { showImages: false, cidUrl: (cid) => `/api/admin/mail/attachment?cid=${encodeURIComponent(cid)}` });
for (const bad of ["<script", "onclick", "<form", "<input", "tracker.example"]) assert.ok(!clean.html.includes(bad), `removed ${bad}`);
assert.ok(clean.html.includes("/api/admin/mail/attachment?cid=ctrl-logo"), "cid resolved to attachment route");
assert.ok(clean.html.includes("#ff4a1c") && clean.html.includes("bgcolor"), "layout CSS kept");
assert.ok(clean.html.includes("<strong>prossimi passi</strong>") && clean.html.includes('href="mailto:info@ctrlagency.dev"'));
assert.ok(clean.blockedImages >= 1, "remote image blocked by default");
assert.ok((p.text ?? "").includes("\n-- \nCtrl Agency"), "text part carries the signature");
assert.equal(stripSignature(p.text ?? ""), body, "draft re-edit strips the signature");
// Screenshot doc: inline the cid as data: so the standalone render shows it, like the attachment route would.
writeFileSync(`${OUT}/branded.html`, emailDocument(clean.html.replace(/\/api\/admin\/mail\/attachment\?cid=ctrl-logo/g, "data:image/png;base64," + makeLogo()), false));

const mdText = "Ciao!\n\n## Punti chiave\n- **Hero** con video breve\n- <b>niente</b> popup <script>x</script>\n\nRiferimento: https://example.com/brief?id=42\nScrivetemi a sara@neristudio.example\n\nSara";
const raw2 = await new MailComposer({ from: "sara@neristudio.example", to: "info@ctrlagency.dev", subject: "md", text: mdText }).compile().build();
const p2 = await simpleParser(raw2, { skipTextToHtml: true, skipImageLinks: true });
assert.equal(p2.html, false, "no html part");
const doc2 = textDocumentBody(p2.text ?? "");
assert.ok(!doc2.includes("<script") && doc2.includes("&lt;b&gt;niente&lt;/b&gt;"), "text escaped");
assert.ok(doc2.includes('href="https://example.com/brief?id=42"') && doc2.includes('href="mailto:sara@neristudio.example"'), "autolinked");
writeFileSync(`${OUT}/plaintext.html`, emailDocument(doc2, false));
writeFileSync(`${OUT}/compose-preview.html`, emailDocument(brandedEmail("Ciao Marco,\n\nin allegato la **proposta** per il logo.\nFammi sapere!").html, false));
console.log("fixture ok ->", OUT);

function makeLogo() {
  // 28x28 orange square PNG generated by zlib, used only for the screenshot.
  const { deflateSync, crc32 } = require_zlib();
  const w = 28, rows = Buffer.alloc((w * 3 + 1) * w);
  for (let y = 0; y < w; y++) for (let x = 0; x < w; x++) { const o = y * (w * 3 + 1) + 1 + x * 3; const c = x > 6 && x < 21 && y > 6 && y < 21 && !(x > 11 && y > 11 && y < 16) ? [12, 12, 12] : [255, 255, 255]; rows.set(c, o); }
  const chunk = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc32(td) >>> 0); return Buffer.concat([l, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(w, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(rows)), chunk("IEND", Buffer.alloc(0))]).toString("base64");
}
function require_zlib() { return process.getBuiltinModule("node:zlib"); }
